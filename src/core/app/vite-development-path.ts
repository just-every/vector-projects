// pnpm's directory decoration identifies the installed dependency graph, not a
// browser capability. Keep the reviewed package/file boundary across lockfile
// refreshes, while retaining an exact allowlist for product source modules.
const packagePath=(path:string)=>path.replace(/^\/node_modules\/\.pnpm\/[^/]+\/node_modules\//,'/browser-package/');
const browserPackageFiles=new Set([...developmentAssets].filter(path=>path.startsWith('/browser-package/')));
export function isViteDevelopmentAsset(pathname: string) {
  if(pathname.includes('..')||pathname.includes('\\')||pathname.includes('%'))return false;
  if(pathname.startsWith('/node_modules/.pnpm/'))return browserPackageFiles.has(packagePath(pathname));
  if(/^\/node_modules\/\.vite\/deps\/rolldown-runtime-[A-Za-z0-9_-]+\.js$/.test(pathname))return true;
  return developmentAssets.has(pathname);
}
