import {readFile, writeFile} from 'node:fs/promises';

const source = new URL('../schema/api-v1.json', import.meta.url);
const target = new URL('./generated.ts', import.meta.url);
const document = JSON.parse(await readFile(source, 'utf8'));
const quote = JSON.stringify;

// Constraints such as date formats, lengths and numeric bounds remain server
// validated. Only types actually declared by the source schema are emitted.
function type(schema) {
  if (schema === false) return 'never';
  if (!schema || schema === true) return 'unknown';
  if (schema.$ref) {
    const prefix = '#/components/schemas/';
    if (!schema.$ref.startsWith(prefix)) throw Error('Unsupported schema reference');
    const name = schema.$ref.slice(prefix.length).replaceAll('~1', '/').replaceAll('~0', '~');
    if (!Object.hasOwn(document.components?.schemas ?? {}, name)) throw Error('Missing schema reference');
    return `Components[${quote(name)}]`;
  }
  if (Object.hasOwn(schema, 'const')) return quote(schema.const);
  if (schema.enum) return schema.enum.map(quote).join(' | ') || 'never';
  for (const key of ['anyOf', 'oneOf', 'allOf']) {
    if (schema[key]) return '(' + schema[key].map(type).join(key === 'allOf' ? ' & ' : ' | ') + ')';
  }
  if (Array.isArray(schema.type)) return schema.type.map(value => type({...schema, type:value})).join(' | ');
  switch (schema.type) {
    case 'string': case 'boolean': case 'null': return schema.type;
    case 'number': case 'integer': return 'number';
    case 'array': return `(${type(schema.items)})[]`;
    case 'object': {
      const required = new Set(schema.required ?? []), properties = schema.properties ?? {};
      const fields = Object.entries(properties).map(([name, value]) => `${quote(name)}${required.has(name) ? '' : '?'}: ${type(value)}`);
      for (const name of required) if (!Object.hasOwn(properties, name)) fields.push(`${quote(name)}: unknown`);
      if (schema.additionalProperties !== false) {
        // An open object's undeclared fields are unknown, never invented models.
        const extra = schema.additionalProperties;
        const value = extra && typeof extra === 'object' && fields.length === 0 ? type(extra) : 'unknown';
        fields.push(`[key: string]: ${value}`);
      }
      return '{ ' + fields.join('; ') + ' }';
    }
    case undefined: return 'unknown';
    default: throw Error('Unsupported schema type: ' + schema.type);
  }
}

const jsonSchema = value => value?.content?.['application/json']?.schema;
const lines = ['// Generated by node sdk/generate.mjs from schema/api-v1.json. Do not edit.',
  '// Missing schema shapes are unknown. Runtime constraints remain enforced by Vector.',
  'export interface Components {'];
for (const [name, schema] of Object.entries(document.components?.schemas ?? {})) lines.push(`  ${quote(name)}: ${type(schema)};`);
lines.push('}', 'export interface Operations {');
const operations = {};
for (const [path, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete', 'head', 'options'].includes(method)) continue;
    const id = operation.operationId;
    if (!id || Object.hasOwn(operations, id)) throw Error('Missing or duplicate operation ID');
    const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])];
    if (parameters.some(p => !['path', 'query'].includes(p.in))) throw Error('Unsupported parameter location');
    const fields = [];
    const pathNames = [...path.matchAll(/\{([^}]+)\}/g)].map(match => match[1]);
    if (pathNames.length) fields.push('path: { ' + pathNames.map(name => `${quote(name)}: ${type(parameters.find(p => p.in === 'path' && p.name === name)?.schema ?? {type:'string'})}`).join('; ') + ' }');
    const query = parameters.filter(p => p.in === 'query');
    if (query.length) fields.push(`query${query.some(p => p.required) ? '' : '?'}: { ` + query.map(p => `${quote(p.name)}${p.required ? '' : '?'}: ${type(p.schema)}`).join('; ') + ' }');
    if (operation.requestBody) fields.push(`body${operation.requestBody.required ? '' : '?'}: ${type(jsonSchema(operation.requestBody))}`);
    const responses = Object.entries(operation.responses);
    const success = responses.filter(([code]) => /^2\d\d$/.test(code)).map(([, response]) => type(jsonSchema(response)));
    const errors = responses.filter(([code]) => !/^2\d\d$/.test(code)).map(([code, response]) => `${quote(code)}: ${type(jsonSchema(response))}`);
    lines.push(`  ${quote(id)}: { input: ${fields.length ? '{ ' + fields.join('; ') + ' }' : 'Record<string, never>'}; output: ${success.join(' | ') || 'unknown'}; errors: { ${errors.join('; ')} } };`);
    operations[id] = {method:method.toUpperCase(), path, scopes:operation['x-scopes'] ?? [], authenticated:(operation.security ?? document.security ?? []).length > 0,
      ...(operation['x-pagination'] ? {pagination:operation['x-pagination']} : {})};
  }
}
lines.push('}', 'export const operations = ' + JSON.stringify(operations, null, 2) + ' as const;', '');
const output = lines.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('SDK is stale; run node sdk/generate.mjs');
} else {
  await writeFile(target, output);
}
console.log(`SDK ${process.argv.includes('--check') ? 'checked' : 'generated'}: ${Object.keys(operations).length} published operations.`);
